import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const generatedDir = path.join(rootDir, 'src', 'types', 'generated');
const manifestPath = path.join(rootDir, 'src-tauri', 'Cargo.toml');

fs.mkdirSync(generatedDir, { recursive: true });
for (const entry of fs.readdirSync(generatedDir)) {
  if (entry.endsWith('.ts')) {
    fs.unlinkSync(path.join(generatedDir, entry));
  }
}

execFileSync(
  'cargo',
  [
    'test',
    '--manifest-path',
    manifestPath,
    '--lib',
    'ts_bindings::export_bindings',
    '--',
    '--exact',
  ],
  {
    cwd: rootDir,
    stdio: 'inherit',
    env: {
      ...process.env,
      TS_RS_EXPORT_DIR: generatedDir,
    },
  },
);

const generatedFiles = fs
  .readdirSync(generatedDir)
  .filter((name) => name.endsWith('.ts') && name !== 'index.ts')
  .sort();

if (generatedFiles.length === 0) {
  throw new Error('ts-rs generated 0 TypeScript binding files.');
}

const lines = [
  '// Auto-generated by ts-rs — DO NOT HAND-EDIT.',
  '// Regenerate via `npm run gen:types`.',
  '',
];
for (const fileName of generatedFiles) {
  const moduleName = fileName.replace(/\.ts$/, '');
  lines.push(`export * from './${moduleName}';`);
}
lines.push('');

fs.writeFileSync(path.join(generatedDir, 'index.ts'), lines.join('\n'), 'utf8');

const prettierBin = path.join(rootDir, 'node_modules', 'prettier', 'bin', 'prettier.cjs');
if (fs.existsSync(prettierBin)) {
  execFileSync(process.execPath, [prettierBin, '--write', generatedDir], {
    cwd: rootDir,
    stdio: 'inherit',
  });
}

console.log(`Generated ${generatedFiles.length} TypeScript binding files in src/types/generated/.`);
